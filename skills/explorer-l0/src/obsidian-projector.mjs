/**
 * One-way accepted-baseline → Obsidian Markdown projection (Todo 11).
 *
 * SQLite is canonical. This module READS the accepted baseline via the store
 * export API and writes a deterministic Markdown projection under a configured
 * root. It NEVER reads Markdown back into SQLite. Projection is one-way.
 *
 * Invariants enforced here:
 *  - Source of truth is the accepted baseline pointer + exported package only.
 *  - Two projections of the same accepted baseline are byte-identical.
 *  - Filenames and Obsidian wikilinks are derived from canonical ids via
 *    idToSlug; relation edges appear only as explicit typed wikilinks.
 *  - No accepted baseline → ProjectionError; existing projection unchanged.
 *  - The projection directory is replaced atomically; on any I/O failure the
 *    previous projection is left intact.
 *  - No absolute paths or raw source bytes are emitted into file contents.
 */

import {
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";

import { ProjectionError } from "./errors.mjs";
import { exportPackage } from "./store.mjs";

export { ProjectionError };

const FILE_MODE = 0o644;
const DIR_MODE = 0o755;

const READ_ONLY_BANNER = [
  "> **READ-ONLY projection.** Generated by Descobrir from the accepted SQLite",
  "> baseline. Do not edit — this file is overwritten on the next projection.",
  "> SQLite is the source of truth; this Markdown is one-way.",
].join("\n");

/**
 * Map a canonical id to a filesystem- and wikilink-safe slug.
 *
 * Canonical ids are produced by src/canonical-id.mjs and contain alphanumerics,
 * ':', '-', and (for relations) '->'. Natural keys may also carry '/' (e.g.
 * 'get:/billing'); those segments would otherwise split a single note across
 * directories. '/' and '\' are replaced with '_' so each canonical id maps to
 * exactly one note file. The transform is idempotent.
 *
 * @param {string} canonicalId
 * @returns {string}
 */
export function idToSlug(canonicalId) {
  if (typeof canonicalId !== "string" || canonicalId === "") {
    throw new ProjectionError("canonical id must be a non-empty string");
  }
  if (canonicalId.includes("\0")) {
    throw new ProjectionError("canonical id contains NUL");
  }
  return canonicalId.replace(/[/\\]/g, "_");
}

/**
 * @param {string} reason
 * @returns {never}
 */
function fail(reason) {
  throw new ProjectionError(reason);
}

/**
 * @param {unknown} value
 * @param {string} label
 * @returns {string}
 */
function requireString(value, label) {
  if (typeof value !== "string" || value === "") {
    fail(`${label} must be a non-empty string`);
  }
  return /** @type {string} */ (value);
}

/**
 * YAML-escape a scalar. We only emit strings/numbers; quote any value that
 * could be misread by a YAML parser. Per YAML, ':' triggers quoting only when
 * followed by a space or at end-of-value; '#' only when preceded by space.
 *
 * @param {string} value
 * @returns {string}
 */
function yamlScalar(value) {
  if (value === "") return '""';
  if (/[\n\r\t]/.test(value)) return JSON.stringify(value);
  if (/:\s|#\s/.test(value) || /:\s*$/.test(value)) return JSON.stringify(value);
  if (/^[-,?[\]{}&*!|>'"%@`]/.test(value)) return JSON.stringify(value);
  return value;
}

/**
 * @param {Record<string, string|number>} fields already-ordered
 * @returns {string}
 */
function renderFrontmatter(fields) {
  const lines = ["---"];
  for (const [key, value] of Object.entries(fields)) {
    lines.push(`${key}: ${yamlScalar(String(value))}`);
  }
  lines.push("---");
  lines.push("");
  return lines.join("\n");
}

/**
 * @param {object} evidence
 * @returns {string}
 */
function renderEvidenceLine(evidence) {
  if (evidence.kind === "artifact") {
    const range =
      evidence.range && typeof evidence.range === "object"
        ? `L${evidence.range.start_line ?? "?"}-L${evidence.range.end_line ?? "?"}`
        : "L?-L?";
    const path = typeof evidence.artifact_path === "string" ? evidence.artifact_path : "<unknown>";
    const manifest =
      typeof evidence.manifest_id === "string" ? evidence.manifest_id : "<unknown>";
    const sha =
      typeof evidence.content_sha256 === "string"
        ? evidence.content_sha256.slice(0, 12)
        : "<unhashed>";
    return `- artifact \`${manifest}\` @ ${path} ${range} (sha256 ${sha}…)`;
  }
  if (evidence.kind === "repository") {
    const uri = typeof evidence.uri === "string" ? evidence.uri : "<unknown>";
    return `- repository \`${uri}\``;
  }
  return `- ${evidence.kind ?? "unknown"}`;
}

/**
 * @param {object} rec
 * @param {object} pkg
 * @returns {{ path: string, content: string }}
 */
function renderRecordFile(rec, pkg) {
  const slug = idToSlug(rec.id);
  /** @type {Record<string, string|number>} */
  const frontmatter = {
    descobrir_projection: "true",
    read_only: "true",
    id: rec.id,
    type: rec.type,
    namespace: pkg.namespace,
    logical_repo: pkg.logical_repo,
    source_revision: pkg.source_revision,
    status: rec.status,
    canonical_graph_hash: pkg.graph_index.canonical_graph_hash,
  };
  const outgoing = pkg.relations
    .filter((r) => r.from_record === rec.id)
    .sort((a, b) => a.id.localeCompare(b.id));
  const incoming = pkg.relations
    .filter((r) => r.to_record === rec.id)
    .sort((a, b) => a.id.localeCompare(b.id));

  /** @type {string[]} */
  const body = [];
  body.push(`# ${rec.type} — ${rec.name}`);
  body.push("");
  body.push(READ_ONLY_BANNER);
  body.push("");
  if (typeof rec.summary === "string" && rec.summary !== "") {
    body.push(rec.summary);
    body.push("");
  }
  body.push("## Attributes");
  body.push("");
  const attrs = rec.attributes && typeof rec.attributes === "object" ? rec.attributes : {};
  const attrKeys = Object.keys(attrs).sort();
  if (attrKeys.length === 0) {
    body.push("_(none)_");
  } else {
    for (const key of attrKeys) {
      body.push(`- ${key}: ${yamlScalar(String(attrs[key]))}`);
    }
  }
  body.push("");
  body.push("## Evidence");
  body.push("");
  if (Array.isArray(rec.evidence) && rec.evidence.length > 0) {
    for (const ev of rec.evidence) {
      body.push(renderEvidenceLine(ev));
    }
  } else {
    body.push("_(none)_");
  }
  body.push("");
  body.push("## Relations (outgoing)");
  body.push("");
  if (outgoing.length === 0) {
    body.push("_(none)_");
  } else {
    for (const rel of outgoing) {
      body.push(`- [[${idToSlug(rel.id)}]] — ${rel.relation_type} → [[${idToSlug(rel.to_record)}]]`);
    }
  }
  body.push("");
  body.push("## Relations (incoming)");
  body.push("");
  if (incoming.length === 0) {
    body.push("_(none)_");
  } else {
    for (const rel of incoming) {
      body.push(
        `- [[${idToSlug(rel.id)}]] — [[${idToSlug(rel.from_record)}]] ${rel.relation_type} →`,
      );
    }
  }
  body.push("");

  return {
    path: join("records", `${slug}.md`),
    content: `${renderFrontmatter(frontmatter)}${body.join("\n")}`,
  };
}

/**
 * @param {object} rel
 * @param {object} pkg
 * @returns {{ path: string, content: string }}
 */
function renderRelationFile(rel, pkg) {
  const slug = idToSlug(rel.id);
  /** @type {Record<string, string|number>} */
  const frontmatter = {
    descobrir_projection: "true",
    read_only: "true",
    id: rel.id,
    relation_type: rel.relation_type,
    from: rel.from_record,
    to: rel.to_record,
    namespace: pkg.namespace,
    logical_repo: pkg.logical_repo,
    source_revision: pkg.source_revision,
    status: rel.status,
    canonical_graph_hash: pkg.graph_index.canonical_graph_hash,
  };

  /** @type {string[]} */
  const body = [];
  body.push(`# ${rel.relation_type} — [[${idToSlug(rel.from_record)}]] → [[${idToSlug(rel.to_record)}]]`);
  body.push("");
  body.push(READ_ONLY_BANNER);
  body.push("");
  body.push(`- From: [[${idToSlug(rel.from_record)}]]`);
  body.push(`- To: [[${idToSlug(rel.to_record)}]]`);
  body.push(`- Type: ${rel.relation_type}`);
  body.push(`- Status: ${rel.status}`);
  body.push("");
  body.push("## Evidence");
  body.push("");
  if (Array.isArray(rel.evidence) && rel.evidence.length > 0) {
    for (const ev of rel.evidence) {
      body.push(renderEvidenceLine(ev));
    }
  } else {
    body.push("_(none)_");
  }
  body.push("");

  return {
    path: join("relations", `${slug}.md`),
    content: `${renderFrontmatter(frontmatter)}${body.join("\n")}`,
  };
}

/**
 * @param {{ pkg: object, accepted: object }} baseline
 * @returns {{ files: Array<{ path: string, content: string }>, summary: object }}
 */
export function renderBaselineProjection(baseline) {
  if (!baseline || typeof baseline !== "object") {
    fail("baseline must be an object with pkg and accepted");
  }
  const { pkg, accepted } = baseline;
  if (!pkg || typeof pkg !== "object") fail("baseline.pkg is required");
  if (!accepted || typeof accepted !== "object") fail("baseline.accepted is required");

  const namespace = requireString(pkg.namespace, "pkg.namespace");
  const logicalRepo = requireString(pkg.logical_repo, "pkg.logical_repo");
  const sourceRevision = requireString(pkg.source_revision, "pkg.source_revision");
  if (!pkg.graph_index || typeof pkg.graph_index.canonical_graph_hash !== "string") {
    fail("pkg.graph_index.canonical_graph_hash is required");
  }
  const graphHash = pkg.graph_index.canonical_graph_hash;
  const records = Array.isArray(pkg.records) ? pkg.records : [];
  const relations = Array.isArray(pkg.relations) ? pkg.relations : [];

  const approver = requireString(accepted.approver, "accepted.approver");
  const acceptedAt = requireString(accepted.accepted_at, "accepted.accepted_at");

  /** @type {{ path: string, content: string }[]} */
  const files = [];

  // README — index + banner.
  /** @type {Record<string, string|number>} */
  const readmeFrontmatter = {
    descobrir_projection: "true",
    read_only: "true",
    namespace,
    logical_repo: logicalRepo,
    source_revision: sourceRevision,
    canonical_graph_hash: graphHash,
    accepted_at: acceptedAt,
    approver,
  };
  const sortedRecords = [...records].sort((a, b) => a.id.localeCompare(b.id));
  const sortedRelations = [...relations].sort((a, b) => a.id.localeCompare(b.id));

  /** @type {string[]} */
  const readme = [];
  readme.push(`# Knowledge baseline — ${namespace} / ${logicalRepo}`);
  readme.push("");
  readme.push(READ_ONLY_BANNER);
  readme.push("");
  readme.push("## Accepted baseline");
  readme.push("");
  readme.push(`- Namespace: \`${namespace}\``);
  readme.push(`- Logical repo: \`${logicalRepo}\``);
  readme.push(`- Source revision: \`${sourceRevision}\``);
  readme.push(`- Canonical graph hash: \`${graphHash}\``);
  readme.push(`- Accepted at: \`${acceptedAt}\``);
  readme.push(`- Approver: \`${approver}\``);
  readme.push(`- Records: ${sortedRecords.length}`);
  readme.push(`- Relations: ${sortedRelations.length}`);
  readme.push("");
  readme.push("## Records");
  readme.push("");
  if (sortedRecords.length === 0) {
    readme.push("_(none)_");
  } else {
    for (const rec of sortedRecords) {
      const slug = idToSlug(rec.id);
      const name = typeof rec.name === "string" ? rec.name : rec.id;
      readme.push(`- [[${slug}]] — ${rec.type}: ${name}`);
    }
  }
  readme.push("");
  readme.push("## Relations");
  readme.push("");
  if (sortedRelations.length === 0) {
    readme.push("_(none)_");
  } else {
    for (const rel of sortedRelations) {
      const slug = idToSlug(rel.id);
      readme.push(
        `- [[${slug}]] — ${rel.relation_type}: [[${idToSlug(rel.from_record)}]] → [[${idToSlug(rel.to_record)}]]`,
      );
    }
  }
  readme.push("");

  files.push({
    path: "README.md",
    content: `${renderFrontmatter(readmeFrontmatter)}${readme.join("\n")}`,
  });

  for (const rec of sortedRecords) {
    files.push(renderRecordFile(rec, pkg));
  }
  for (const rel of sortedRelations) {
    files.push(renderRelationFile(rel, pkg));
  }

  // Stable file ordering by path so two renders produce identical file lists.
  files.sort((a, b) => a.path.localeCompare(b.path));

  const summary = {
    namespace,
    logical_repo: logicalRepo,
    source_revision: sourceRevision,
    canonical_graph_hash: graphHash,
    record_count: records.length,
    relation_count: relations.length,
    file_count: files.length,
  };

  return { files, summary };
}

/**
 * Reject out_dir shapes that could escape the projection root or replace a
 * foreign path. out_dir must be caller-supplied and absolute; we do NOT create
 * parents above the leaf the caller named.
 *
 * @param {string} outDir
 * @returns {string}
 */
function validateOutDir(outDir) {
  const raw = requireString(outDir, "out_dir");
  if (raw.includes("\0")) fail("out_dir contains NUL");
  if (!isAbsolute(raw)) fail("out_dir must be an absolute path");
  // Reject traversal segments — out_dir itself is the projection root.
  const parts = raw.split(/[/\\]/);
  for (const part of parts) {
    if (part === "..") fail("out_dir must not contain '..' segments");
  }
  return resolve(raw);
}

/**
 * Atomic-replace the projection directory with the rendered files.
 *
 * Strategy: stage into a sibling temp dir under the same parent, then rename.
 * On POSIX, rename of a directory within the same filesystem is atomic, so a
 * crash before rename leaves the prior projection intact and a crash after
 * leaves either the prior or the new projection, never a torn mix.
 *
 * If out_dir does not yet exist, the staged temp directory is renamed into
 * place directly. We never follow symlinks for the existing out_dir — a
 * symlinked projection root is rejected to avoid clobbering foreign targets.
 *
 * @param {string} outDir absolute projection root
 * @param {{ files: Array<{ path: string, content: string }> }} rendered
 */
export function writeProjectionAtomic(outDir, rendered) {
  const root = validateOutDir(outDir);
  if (!rendered || !Array.isArray(rendered.files)) {
    fail("rendered.files must be an array");
  }

  // Validate and dedupe relative paths so we never escape the staged root.
  const seenPaths = new Set();
  for (const file of rendered.files) {
    if (!file || typeof file.path !== "string" || file.path === "") {
      fail("each rendered file must have a non-empty path");
    }
    if (typeof file.content !== "string") fail("each rendered file content must be a string");
    const normalized = file.path.replace(/\\/g, "/").replace(/^\/+/, "");
    const parts = normalized.split("/");
    for (const part of parts) {
      if (part === ".." || part === "") {
        fail(`rendered file path must be relative without traversal: ${file.path}`);
      }
    }
    if (seenPaths.has(normalized)) {
      fail(`duplicate rendered file path: ${normalized}`);
    }
    seenPaths.add(normalized);
    // Re-assign so we read back the cleaned form later.
    file._normalized = normalized;
  }

  const parent = dirname(root);
  const base = root.split(sep).pop() || "descobrir-projection";
  const tmp = join(
    parent,
    `.${base}.tmp.${process.pid}.${Date.now()}.${Math.random().toString(36).slice(2, 10)}`,
  );

  // Reject if existing root is a symlink — never clobber a foreign target.
  if (existsSync(root)) {
    let st;
    try {
      st = lstatSync(root);
    } catch (err) {
      fail(`failed to stat existing projection: ${err instanceof Error ? err.message : String(err)}`);
    }
    if (st.isSymbolicLink()) fail("out_dir must not be a symlink");
  }

  try {
    mkdirSync(tmp, { recursive: true, mode: DIR_MODE });
    for (const file of rendered.files) {
      const target = join(tmp, /** @type {string} */ (file._normalized));
      mkdirSync(dirname(target), { recursive: true, mode: DIR_MODE });
      writeFileSync(target, file.content, { encoding: "utf8", mode: FILE_MODE });
    }

    // Atomic swap. On POSIX, rename over an existing dir requires it to be
    // empty; we use a backup-rename-then-promote sequence instead.
    let backup = null;
    if (existsSync(root)) {
      backup = join(
        parent,
        `.${base}.old.${process.pid}.${Date.now()}.${Math.random().toString(36).slice(2, 10)}`,
      );
      renameSync(root, backup);
    }
    try {
      renameSync(tmp, root);
    } catch (err) {
      if (backup !== null && existsSync(backup)) {
        try { renameSync(backup, root); } catch { /* best-effort restore */ }
      }
      fail(`failed to swap projection directory: ${err instanceof Error ? err.message : String(err)}`);
    }
    if (backup !== null && existsSync(backup)) {
      try { rmSync(backup, { recursive: true, force: true }); } catch { /* best-effort */ }
    }
  } catch (err) {
    if (existsSync(tmp)) {
      try { rmSync(tmp, { recursive: true, force: true }); } catch { /* best-effort */ }
    }
    if (err instanceof ProjectionError) throw err;
    fail(`failed to write projection: ${err instanceof Error ? err.message : String(err)}`);
  } finally {
    // Clean the normalized mirror field off the caller's objects.
    for (const file of rendered.files) {
      delete file._normalized;
    }
  }
}

/**
 * Top-level: read the accepted baseline from the store and project it.
 *
 * Reads ONLY the accepted baseline pointer and the exported package. Never
 * reads Markdown back. Throws ProjectionError if no accepted baseline exists;
 * in that case the existing projection is left untouched.
 *
 * @param {{ getAcceptedBaseline: Function, _db?: unknown }} store
 * @param {{ namespace: string, logical_repo: string, out_dir: string }} input
 * @returns {{ summary: object, accepted: object }}
 */
export function projectAcceptedBaseline(store, input) {
  if (!store || typeof store !== "object") fail("store is required");
  if (!input || typeof input !== "object") fail("input is required");
  const namespace = requireString(input.namespace, "namespace");
  const logicalRepo = requireString(input.logical_repo, "logical_repo");
  const outDir = validateOutDir(input.out_dir);

  const accepted = store.getAcceptedBaseline({ namespace, logical_repo: logicalRepo });
  if (!accepted) {
    fail(`no accepted baseline for namespace '${namespace}' / logical_repo '${logicalRepo}'`);
  }

  const pkg = exportPackage(store, { accepted: true, namespace, logical_repo: logicalRepo });
  const rendered = renderBaselineProjection({ pkg, accepted });
  writeProjectionAtomic(outDir, rendered);
  return { summary: rendered.summary, accepted };
}
